"""v1.5.5 Help: README.md (install, how to use) and CONTROLS.md (controls) rendered at build time into page textures
(assets/help_NN.png, 1024x768, DejaVu Sans) and embedded as text in src/sixth_sense.lua between the HELP DOCS markers
(HELP_PAGES: texture ids and sizes; HELP_TEXT: the plain text). Run by tools/build.py before every build, so the zip
always carries the current docs and needs nothing from the repo at run time.
  python3 tools/help_pages.py"""
import re, sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE.parent / 'BingusSharedLoader/scripts'))
from archive import resource_hash
FONT, BOLD = HERE / 'tools/fonts/DejaVuSans.ttf', HERE / 'tools/fonts/DejaVuSans-Bold.ttf'
W, H, M = 1024, 768, 34
DOCS = [('README', 'README.md'), ('CONTROLS', 'CONTROLS.md')]
PREFIX = 'mods/darryl/sixth_sense/help_'
BEGIN, END = '-- BEGIN HELP DOCS', '-- END HELP DOCS'

def inline(t):
    t = re.sub(r'!\[[^\]]*\]\([^)]*\)', '', t)
    t = re.sub(r'\[([^\]]+)\]\((https?://[^)]*)\)', lambda m: m.group(1) if m.group(1) == m.group(2) else '%s (%s)' % (m.group(1), m.group(2)), t)   # (v1.5.6: web links keep their URL)
    t = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', t)
    t = t.replace('**', '').replace('`', '')
    return t.strip()

def blocks(md):
    """(kind, text): h1 / h2 / h3 / p / li / row / gap"""
    out = []
    for raw in md.splitlines():
        s = raw.rstrip()
        if not s.strip(): out.append(('gap', '')); continue
        if re.match(r'^\s*!\[', s): continue
        if re.match(r'^\|?\s*:?-{3,}', s): continue
        m = re.match(r'^(#{1,3})\s+(.*)', s)
        if m: out.append(('h%d' % len(m.group(1)), inline(m.group(2)))); continue
        if s.lstrip().startswith('|'):
            cells = [inline(c) for c in s.strip().strip('|').split('|')]
            out.append(('row', '  ·  '.join(c for c in cells if c))); continue
        s2 = re.sub(r'^\s*>\s?', '', s)
        m = re.match(r'^(\s*)([-*]|\d+\.)\s+(.*)', s2)
        if m: out.append(('li', ('  ' * (len(m.group(1)) // 2)) + ('• ' if m.group(2) in '-*' else m.group(2) + ' ') + inline(m.group(3)))); continue
        if out and (out[-1][0] == 'p' or (out[-1][0] == 'li' and raw.startswith(' '))) and not raw.startswith('>'):   # (a paragraph's next line)
            out[-1] = (out[-1][0], out[-1][1] + ' ' + inline(s2)); continue
        out.append(('p', inline(s2)))
    return out

STYLE = {'h1': (BOLD, 30, (140, 255, 170), 40), 'h2': (BOLD, 24, (140, 255, 170), 34), 'h3': (BOLD, 21, (255, 230, 120), 30),
         'p': (FONT, 18, (235, 235, 235), 25), 'li': (FONT, 18, (235, 235, 235), 25), 'row': (FONT, 17, (220, 230, 255), 24)}

def wrap(text, font, width):
    ind = len(text) - len(text.lstrip(' '))
    words, lines, cur = text.split(' '), [], ''
    for w in words:
        t = (cur + ' ' + w) if cur else w
        if font.getlength(t) <= width or not cur: cur = t
        else: lines.append(cur); cur = ' ' * (ind + 2) + w
    if cur: lines.append(cur)
    return lines

def pages_of(name, md):
    lines = []                                   # (font, size, colour, height, text)
    for kind, text in blocks(md):
        if kind == 'gap':
            if lines and lines[-1][4] != '': lines.append((None, 0, None, 10, ''))
            continue
        fp, sz, col, lh = STYLE[kind]
        f = ImageFont.truetype(str(fp), sz)
        if kind.startswith('h') and lines: lines.append((None, 0, None, 8, ''))
        for l in wrap(text, f, W - 2 * M): lines.append((f, sz, col, lh, l))
    pages, cur, y = [], [], 0
    for ln in lines:
        if y + ln[3] > H - 2 * M - 30 and cur: pages.append(cur); cur, y = [], 0
        if not cur and ln[0] is None: continue
        cur.append(ln); y += ln[3]
    if cur: pages.append(cur)
    return pages

def render(all_pages):
    imgs, n = [], len(all_pages)
    foot = ImageFont.truetype(str(FONT), 15)
    for i, (doc, pg) in enumerate(all_pages):
        im = Image.new('RGBA', (W, H), (10, 14, 20, 238)); d = ImageDraw.Draw(im)
        d.rectangle((0, 0, W - 1, H - 1), outline=(90, 255, 140, 255), width=3)
        y = M
        for f, sz, col, lh, t in pg:
            if f: d.text((M, y), t, font=f, fill=col + (255,))
            y += lh
        d.text((M, H - M - 8), 'Sixth Sense help: %s   page %d / %d   (wheel or click the left / right half: page; click outside or Help: close)' % (doc, i + 1, n), font=foot, fill=(170, 180, 190, 255))
        imgs.append(im)
    return imgs

def lua_block(rows, text):
    assert ']==]' not in text
    out = [BEGIN + ' (generated by tools/help_pages.py from README.md and CONTROLS.md at build time; do not edit)',
           'local HELP_PAGES = {']
    out += ["  { '%016x', %d, %d, \"%s\" }," % r for r in rows]
    out += ['}', 'local HELP_TEXT = [==[', text.rstrip('\n'), ']==]', END]
    return '\n'.join(out)

def generate(write=True):
    all_pages, text = [], []
    for doc, fn in DOCS:
        md = (HERE / fn).read_text(encoding='utf-8')
        text.append('==== %s (%s) ====\n%s' % (doc, fn, md))
        all_pages += [(doc, p) for p in pages_of(doc, md)]
    imgs = render(all_pages)
    names, rows = [], []
    for old in (HERE / 'assets').glob('help_*.png'): old.unlink()
    for i, im in enumerate(imgs, 1):
        key = 'help_%02d' % i
        im.save(HERE / 'assets' / (key + '.png'))
        names.append((PREFIX + '%02d' % i, key + '.png'))
        rows.append((resource_hash(PREFIX + '%02d' % i), W, H, all_pages[i - 1][0]))
    lua_p = HERE / 'src/sixth_sense.lua'
    src = lua_p.read_text(encoding='utf-8')
    a, b = src.index(BEGIN), src.index(END) + len(END)
    new = src[:a] + lua_block(rows, '\n'.join(text)) + src[b:]
    if write and new != src: lua_p.write_text(new, encoding='utf-8')
    return names

if __name__ == '__main__':
    n = generate(); print('help pages:', len(n))
